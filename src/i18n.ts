import { traditionalMessages } from "./i18n.zhTW";
export type UiLanguage = "en" | "zh-CN" | "zh-TW";
export type LanguageSetting = "auto" | UiLanguage;
export const LANGUAGE_SETTINGS: readonly LanguageSetting[] = ["auto", "zh-CN", "zh-TW", "en"];

export function resolveUiLanguage(setting: unknown, vscodeLanguage: string): UiLanguage {
  const value = setting === "auto" || !LANGUAGE_SETTINGS.includes(setting as LanguageSetting) ? vscodeLanguage : String(setting);
  if (/^zh[-_](tw|hk|mo|hant)/i.test(value)) return "zh-TW";
  if (/^zh/i.test(value)) return "zh-CN";
  return "en";
}

