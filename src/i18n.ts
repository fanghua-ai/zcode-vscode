const englishSources = Object.fromEntries(Object.entries(messages).map(([key, value]) => [value, key]));
let language: UiLanguage = "zh-CN";
export class LocalizedError extends Error {
  readonly code: string;
  constructor(readonly key: string, readonly values: Record<string, unknown> = {}, options?: ErrorOptions) {
    super(translate(key, "zh-CN", values), options);
    this.name = "LocalizedError";
    this.code = key;
  }
}
export function setUiLanguage(value: UiLanguage): void { language = value; }
export function getUiLanguage(): UiLanguage { return language; }
function variant(text: string, locale: UiLanguage): string {
  if (locale === "en") return messages[text] ?? text;
  if (locale === "zh-TW") return traditionalMessages[text] ?? text;
  return text;
}
export function translate(text: string, locale: UiLanguage, values: Record<string, unknown> = {}): string {
  const source = aliases[text] ?? englishSources[text] ?? text;
  return variant(source, locale).replace(/\{(\d+)\}/g, (match, key) => key in values ? String(values[key]) : match);
}
export function t(text: string, values?: Record<string, unknown>): string { return translate(text, language, values); }

/** Exact fixed labels only. Dynamic labels must retain their key and parameters. */
export function relocalizeUiText(text: string): string {
  for (const source of Object.keys(messages)) {
    if (source.includes("{")) continue;
    for (const locale of ["zh-CN", "zh-TW", "en"] as const) {
      if (text === variant(source, locale)) return t(source);
    }
  }
  return text;
}
